#!/usr/bin/env python3
"""
Writes components/comp-card/library.ts from Ola Szkolda's library.

  xcrun swiftc -O -sdk "$(xcrun --show-sdk-path)" faces.swift -o .faces
  ./.faces ../../public/home/library/*.webp > faces.jsonl
  python3 build-data.py

The shot tags are pholio-app's frame taxonomy, tagged by hand against each
picture (public/landing/data.js carries the original tagging). The face box
is Apple Vision's; where Vision finds no face (backs, details), the anchor
below places the photograph on her figure by hand, in face units.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.abspath(os.path.join(HERE, "..", ".."))

src = open(os.path.join(SITE, "public/landing/data.js")).read()
SHOT = {a: c for a, b, c in re.findall(r'"id":"([^"]+)","p":(\d+),"shot":"([^"]+)"', src)}
LG = {f[:-5] for f in os.listdir(os.path.join(SITE, "public/home/library-lg"))}

# No face in frame: [x, y] of the photograph's centre from her face, and its
# height, all in face heights.
MANUAL = {
    "0FapEC6FwtA": (0.6, 8.8, 3.4),   # her feet, heels
    "2CzjHAuVJ_s": (0.9, 4.9, 3.2),   # the bag at her hip
    "NpBfwUPnDK4": (-0.7, 4.5, 3.0),  # the bag in her hands
    "gKEFqs0tYAc": (0.2, 2.4, 2.6),   # her hand at the necklace
    "fBsn-7LlsN0": (0.3, 3.7, 2.8),   # the ring box in her hands
}
# Vision found the body but not the face: fh is a typical figure for the shot.
FIGURE_FH = {"full_length": 0.066, "back": 0.13}

RANK = {"full_length": 0, "three_quarter": 1, "detail": 1.5, "half_body": 2,
        "profile": 2, "back": 2, "headshot": 3}

HERO = "T6QKnkoltks"

items = []
for line in open(os.path.join(HERE, "faces.jsonl")):
    d = json.loads(line)
    id_ = d["file"][:-5]
    shot = SHOT[id_]
    it = {"id": id_, "shot": shot, "aspect": round(d["w"] / d["h"], 4)}
    if "face" in d:
        fx, fy, fw, fh = d["face"]
        it["face"] = [round(fx + fw / 2, 4), round(fy + fh / 2, 4), round(fh, 4)]
    elif id_ in MANUAL:
        it["place"] = list(MANUAL[id_])
    else:
        head = d["pose"]["head_joint"]
        it["face"] = [round(head[0], 4), round(head[1], 4), FIGURE_FH[shot]]
    if id_ in LG:
        it["lg"] = True
    items.append(it)

def depth(it):
    if it["id"] == HERO:
        return (-1, 0)
    fh = it["face"][2] if "face" in it else 1 / it["place"][2]
    return (RANK[it["shot"]], fh)

items.sort(key=depth)

out = [
    "/**",
    " * Her library: sixty of Ola Szkolda's own photographs, as she uploads them",
    " * to Unsplash (@olaszkolda), from ten sittings. This is the material a",
    " * talent brings to Pholio; Pholio made none of it (`lessons.md` §49).",
    " *",
    " * Generated by `scripts/home-library/build-data.py`. Do not edit by hand.",
    " *",
    " * Ordered bottom to top as the photographs lie in the nest: widest framing",
    " * at the bottom, tightest on top, and the frame that leads beneath them all.",
    " *",
    " *   shot    pholio-app's frame taxonomy, tagged against the picture",
    " *   aspect  width over height",
    " *   face    [centre x, centre y, height], fractions of the photograph",
    " *           (Apple Vision), where she is in it",
    " *   place   no face in frame: [x, y, height] from her face, in face heights",
    " *   lg      a 1100px-wide copy exists in /home/library-lg",
    " */",
    "",
    'export type Shot = "headshot" | "half_body" | "three_quarter" | "full_length" | "profile" | "back" | "detail";',
    "",
    "export type LibraryItem = {",
    "  id: string;",
    "  shot: Shot;",
    "  aspect: number;",
    "  face?: [number, number, number];",
    "  place?: [number, number, number];",
    "  lg?: boolean;",
    "};",
    "",
    "export const LIBRARY: LibraryItem[] = [",
]
for it in items:
    out.append("  " + json.dumps(it, separators=(", ", ": ")).replace('"id"', "id").replace('"shot"', "shot").replace('"aspect"', "aspect").replace('"face"', "face").replace('"place"', "place").replace('"lg"', "lg") + ",")
out.append("];")
open(os.path.join(SITE, "components/comp-card/library.ts"), "w").write("\n".join(out) + "\n")
print(len(items), "items")
